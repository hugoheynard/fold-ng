// Regenerates demo/shell/changelog.generated.ts — the structured CHANGELOG that
// powers the designed `/changelog` timeline page. Parsing lives in Node (shared
// with the release flow via scripts/lib/changelog.mjs) so the gallery ships a
// typed, SSR-safe data file with no markdown parser at runtime.
//
// Wired to `predev:build` (the deployed gallery is always fresh) and `pnpm stats`.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseChangelog } from "./lib/changelog.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "demo/shell/changelog.generated.ts");

const releases = parseChangelog(
  readFileSync(join(root, "CHANGELOG.md"), "utf8"),
);
const published = releases.find((r) => !r.unreleased)?.version ?? "0.0.0";

if (releases.length === 0) {
  throw new Error("gen-changelog: no releases parsed from CHANGELOG.md");
}

const body = `// GENERATED by scripts/gen-changelog.mjs — do not edit by hand.
// The CHANGELOG, parsed into structured releases for the /changelog timeline
// page. Refreshed on \`predev:build\` and \`pnpm stats\`.

/** A safe inline run of a changelog line (no runtime markdown parsing). */
export interface ChangelogRun {
  readonly kind: "text" | "code" | "strong";
  readonly value: string;
}

/** One bullet: a bold lead, the rest of the prose, and a breaking flag. */
export interface ChangelogEntry {
  readonly lead: readonly ChangelogRun[];
  readonly rest: readonly ChangelogRun[];
  readonly breaking: boolean;
}

/** A \`### Added\` / \`### Fixed\` … block within a release. */
export interface ChangelogGroup {
  readonly kind: string;
  readonly items: readonly ChangelogEntry[];
}

/** One release section (\`[Unreleased]\` or \`[x.y.z] - date\`). */
export interface ChangelogRelease {
  readonly version: string;
  readonly date: string | null;
  readonly unreleased: boolean;
  readonly counts: Readonly<Record<string, number>>;
  readonly breaking: number;
  readonly groups: readonly ChangelogGroup[];
}

/** Every release, newest first — \`[Unreleased]\` leads when non-empty. */
export const CHANGELOG: readonly ChangelogRelease[] = ${JSON.stringify(
  releases,
  null,
  2,
)};

/** The latest published version (== npm \`latest\`), for dev-vs-npm badges. */
export const PUBLISHED_VERSION = ${JSON.stringify(published)};
`;

writeFileSync(out, body);
execFileSync("npx", ["prettier", "--write", out], {
  cwd: root,
  stdio: "ignore",
});
console.log(
  `gen-changelog: ${releases.length} releases, published ${published} → ${out}`,
);
